/* joriy til (localStorage dan o'qiladi, default: ru) */
let currentLang = localStorage.getItem('rb_lang') || 'ru';

function t(key) {
  return (TRANSLATIONS[currentLang] && TRANSLATIONS[currentLang][key]) || TRANSLATIONS['ru'][key] || key;
}

function setLang(lang) {
  currentLang = lang;
  localStorage.setItem('rb_lang', lang);
  document.documentElement.lang = lang;
  applyTranslations();
  /* tilga bog'liq narsalarni qayta render qilish */
  if (typeof renderChips === 'function') renderChips();
  if (typeof renderGrid  === 'function') renderGrid();
  if (typeof renderCart  === 'function') renderCart();
  /* til tugmalarini yangilash */
  document.querySelectorAll('.lang-btn').forEach(b => {
    b.classList.toggle('on', b.dataset.lang === lang);
  });
}

function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    const val = t(key);
    if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
      el.placeholder = val;
    } else if (el.dataset.i18nAttr) {
      el.setAttribute(el.dataset.i18nAttr, val);
    } else {
      el.textContent = val;
    }
  });
  /* title */
  document.title = currentLang === 'uz'
    ? 'Red Bull Energy — Energiya, tezlik, adrenalin'
    : 'Red Bull Energy — Энергия, скорость, адреналин';
}

